// Появление элементов списка «лесенкой».
//
// Потолок обязателен: без него двадцатый вагон при шаге 70 мс выезжал через
// полторы секунды, а полсотни — через три с половиной. Пользователь читает
// это как «сайт тормозит», хотя данные давно пришли. С потолком лесенка
// видна на первых элементах и заканчивается вместе с ними.
const STEP_MS = 40;
const MAX_MS = 240;

/** Значение для style.animationDelay у i-го элемента списка. */
export function revealDelay(index: number): string {
  return `${Math.min(index * STEP_MS, MAX_MS)}ms`;
}
