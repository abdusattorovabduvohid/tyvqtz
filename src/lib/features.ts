// Выключатели разделов системы. Меняются ПРЯМО ЗДЕСЬ, в коде: поставил
// true/false → задеплоил. Ничего больше править не нужно.

// ─────────────────────────── Уведомления ───────────────────────────
//
//   true  — Web Push и Telegram работают: пункт «Уведомления» в меню,
//           страница настроек, отправка на события, ежедневный крон.
//   false — раздела нет вообще: пункт меню и страница скрыты, API отвечает
//           404, уведомления не отправляются, PushAutoHeal молчит.
//
// Выключение НИЧЕГО не ломает и не удаляет: подписки устройств и привязки
// телеграма остаются в базе. Вернёте true — всё заработает как было.
export const NOTIFICATIONS_ENABLED = true;

// Что из уведомлений видно сотрудникам: пункт меню и страница «Уведомления»,
// колонка телеграма в списке людей, автопочинка push-подписок в браузере.
//
// Отдельно от NOTIFICATIONS_ENABLED: бот и отправка уже нужны (тревоги
// суперадмину, ответ на /start), а раздел для сотрудников ещё не готов к
// показу. Без самой отправки UI бессмыслен, поэтому флаг её не обходит.
export const NOTIFICATIONS_UI_ENABLED = NOTIFICATIONS_ENABLED && false;
